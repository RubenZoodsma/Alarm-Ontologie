"""
summary_stats.py

Computes every number in the manuscript's "5.1.4 Summary statistics"
paragraph (AlarmOnto_V4.docx) directly from the live ontology / vocabulary /
knowledge-graph pipeline, so the reported figures cannot drift from what the
pipeline actually produces. Writes a ready-to-paste Markdown snippet to
DOCS/tables/summary_stats.md, mirroring corpus_stats.py's convention.

What each manuscript figure maps to
------------------------------------
  Unique alarm messages annotated       rows of DATA/ANNOTATION/consensus/
                                         p50_annotated.csv
  Triples before enrichment             the SAME ontology-driven builder
  Triples after enrichment              build_framework.py uses (build_alarmtype_
  Median triples/alarm before/after     triples), called on two versions of the
                                         annotated CSV: the real one ("after"),
                                         and a copy with every column blanked
                                         except alarmLabel/alarmPriority
                                         ("before" — exactly the fields present
                                         in the raw DATA/CORPUS/*.csv,
                                         pre-annotation). Reusing the real
                                         builder (never re-implementing it)
                                         means "before" is not a guess at what
                                         translation would produce — it is
                                         what the pipeline actually produces
                                         when handed only that information.
  MDA ontology classes / object         FRAMEWORK/ONTOLOGY/ontology.ttl, by owl:Class /
  properties / datatype properties      owl:ObjectProperty / owl:DatatypeProperty
  SKOS concepts / concept schemes       vocab_base.ttl UNION the concept stubs
                                         build_framework.py's own builder would
                                         generate for the current CSV (not the
                                         possibly-stale FRAMEWORK/VOCABULARY/
                                         vocab_generated.ttl on disk — regenerated
                                         in-process so this can't go stale either).
  Retrospective PoC events / triples    DATA/POC_EVENTS/events_data.csv row count;
                                         kg_inference.trig's default graph
                                         (the accumulated structural
                                         translation — see that file's own
                                         header for why named-graph ticks,
                                         which include OWL-reasoner
                                         entailments, are excluded).
  Resource utilization (classes /       owl:Class / owl:ObjectProperty / skos:Concept
  relations / concepts exercised)       usage counted over the OWL-RL closure (owlrl,
                                         same reasoner cq_QA.py/op_knowledge.py use) of
                                         onto+inference+the current KG — NOT a raw
                                         rdf:type scan, which undercounts badly (see
                                         resource_utilization_stats()'s docstring for
                                         why). Reported against the current annotation
                                         stage (pct_of_types), not as a design verdict.

Data-provenance caveat — read before citing the retrospective PoC numbers
---------------------------------------------------------------------------
DATA/POC_EVENTS/events_data.csv is currently SYNTHETIC placeholder data
generated by events_seed.py "for load and concurrency testing" (see that
script's own docstring) — it is explicitly NOT the authored real-world
alarm log. The numbers this script prints for the retrospective PoC section
are real outputs of the current pipeline, but they describe synthetic data,
not the real-world retrospective cohort the manuscript claims. Replace
events_data.csv with the authored dataset before citing those two numbers.

Usage
-----
  python3 summary_stats.py
"""

