def main() -> None:
    rep = alarm_representation_stats()
    retro = retrospective_stats()

    print(f"[corpus]     {rep['n_alarms']} unique annotated alarm messages "
          f"({rep['pct_of_types']:.1f}% of {rep['n_total_types']} unique alarm types), "
          f"representing {rep['pct_of_volume']:.1f}% of total alarm volume")
    print(f"[triples]    before enrichment: {rep['triples_before']} "
          f"(median {rep['median_before']:.0f}/alarm)")
    print(f"[triples]    after enrichment:  {rep['triples_after']} "
          f"(median {rep['median_after']:.0f}/alarm)")
    print(f"[triples]    increase: {rep['pct_increase']:.1f}%")
    print(f"[ontology]   {rep['n_classes']} classes, {rep['n_object_props']} object properties, "
          f"{rep['n_datatype_props']} datatype properties")
    print(f"[vocab]      {rep['n_concepts']} concepts across {rep['n_schemes']} concept schemes")
    print(f"[util]       classes: {rep['pct_classes_used']:.1f}% ({rep['n_classes_used']}/{rep['n_classes_total']}), "
          f"relations: {rep['pct_relations_used']:.1f}% ({rep['n_relations_used']}/{rep['n_relations_total']}), "
          f"concepts: {rep['pct_concepts_used']:.1f}% ({rep['n_concepts_used']}/{rep['n_concepts_total']})")
    print(f"[util]       always-present classes (structural, not data-dependent): "
          f"{', '.join(rep['always_present_classes'])}")
    print(f"[retro]      {retro['n_events']} events, {retro['n_triples']} triples "
          f"(default graph); {retro['n_triples_all_ticks_deduped']} triples if all "
          f"{retro['n_ticks']} ticks' snapshots are included")
    if rep["on_disk_note"]:
        print(rep["on_disk_note"])

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(render_markdown(rep, retro), encoding="utf-8")
